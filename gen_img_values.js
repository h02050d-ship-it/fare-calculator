function seinoCost(tIdx,dIdx){ return Math.ceil(SEINO_FARES[tIdx][dIdx]*SEINO_DISCOUNT*(1+FUEL_SC_RATE)/10)*10; }
function priceZeinuki(baseAll){ return Math.ceil(baseAll*EC_MULT/100)*100; }
function tierOf(W){ return SEINO_WEIGHTS.findIndex(v=>v>=W); }
function priceSingle(pref,len,taba){
  if (QUOTE_ONLY_2M.includes(pref)) return null;
  const d=DANBALL[len], dist=PREF_TO_DIST[SEINO_PREF_MAP[pref]];
  let fareSum=0,boxSum=0;
  if (taba<=MAX_BUNDLE){ const ti=tierOf(Math.ceil(taba*d.weight)); if(ti===-1)return null; fareSum=seinoCost(ti,dist); boxSum=taba*d.box; }
  else { const ships=Math.ceil(taba/MAX_BUNDLE), baseQ=Math.floor(taba/ships), rem=taba%ships;
    for(let i=0;i<ships;i++){ const sq=baseQ+(i<rem?1:0); const ti=tierOf(Math.ceil(sq*d.weight)); if(ti===-1)return null; fareSum+=seinoCost(ti,dist); boxSum+=sq*d.box; } }
  return priceZeinuki(fareSum+boxSum); // 税抜
}
const zeikomi = z => z==null?null:Math.round(z*1.1);
